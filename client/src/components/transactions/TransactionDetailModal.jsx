import { useEffect, useState } from 'react';
import Modal from '../ui/Modal';
import Button from '../forms/Button';
import Loading from '../ui/Loading';
import { transactionApi } from '../../services/transactionApi';
import { formatMoney, formatDate } from '../../utils/format';

function DetailRow({ label, value }) {
  return (
    <div className="flex justify-between gap-4 py-2 border-b border-gray-50 last:border-0">
      <dt className="text-sm text-gray-500 shrink-0">{label}</dt>
      <dd className="text-sm text-gray-900 text-right break-words">{value}</dd>
    </div>
  );
}

/**
 * Transaction detail view.
 *
 * Data comes from `GET /api/transactions/:id`, whose serializer returns only
 * user-facing fields (type, amount, dates, notes, reference, account, category,
 * recurrence link) — internal columns such as `userId` are never sent.
 *
 * The presentation is exported separately so tests can render it with a fixture
 * without needing a live request.
 */
export function TransactionDetailBody({ transaction, onEdit, onDuplicate, onDelete }) {
  const isIncome = transaction?.type === 'INCOME';

  if (!transaction) return null;

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between gap-4">
        <div>
          <p className={`text-3xl font-bold ${isIncome ? 'text-green-600' : 'text-danger-600'}`}>
            {isIncome ? '+' : '−'}{formatMoney(transaction.amount, transaction.account?.currency)}
          </p>
          <p className="text-sm text-gray-500 mt-1">{formatDate(transaction.date)}</p>
        </div>
        <div className="flex flex-col items-end gap-1.5">
          <span className={`text-xs font-medium px-2 py-1 rounded-full ${isIncome ? 'bg-green-50 text-green-700' : 'bg-danger-50 text-danger-700'}`}>
            {isIncome ? 'Income' : 'Expense'}
          </span>
          {transaction.isAutoGenerated && (
            <span className="text-[10px] font-medium px-1.5 py-0.5 rounded bg-indigo-50 text-indigo-600">
              Auto-generated
            </span>
          )}
        </div>
      </div>

      <dl className="space-y-0">
        <DetailRow label="Description" value={transaction.description || '—'} />
        <DetailRow
          label="Category"
          value={transaction.category
            ? `${transaction.category.icon} ${transaction.category.name}`
            : '—'}
        />
        <DetailRow label="Account" value={transaction.account?.name || '—'} />
        <DetailRow label="Notes" value={transaction.notes || '—'} />
        <DetailRow label="Reference" value={transaction.reference || '—'} />
        {transaction.recurringExpense && (
          <DetailRow
            label="Recurring source"
            value={`${transaction.recurringExpense.name} (${transaction.recurringExpense.frequency})`}
          />
        )}
        <DetailRow label="Created" value={new Date(transaction.createdAt).toLocaleString('en-IN')} />
        <DetailRow label="Last updated" value={new Date(transaction.updatedAt).toLocaleString('en-IN')} />
      </dl>

      <div className="flex flex-wrap justify-end gap-2 pt-4 border-t border-gray-100">
        <Button variant="secondary" size="sm" onClick={() => onDuplicate(transaction)}>
          Duplicate
        </Button>
        <Button variant="secondary" size="sm" onClick={() => onDelete(transaction)}>
          Delete
        </Button>
        <Button variant="primary" size="sm" onClick={() => onEdit(transaction)}>
          Edit
        </Button>
      </div>
    </div>
  );
}

export default function TransactionDetailModal({ transactionId, onClose, onEdit, onDuplicate, onDelete }) {
  const [transaction, setTransaction] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  useEffect(() => {
    if (!transactionId) return undefined;
    let cancelled = false;
    setLoading(true);
    setError(null);
    setTransaction(null);
    transactionApi
      .get(transactionId)
      .then((data) => {
        if (!cancelled) setTransaction(data.transaction);
      })
      .catch((err) => {
        if (!cancelled) setError(err.response?.data?.error || 'Failed to load transaction');
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [transactionId]);

  return (
    <Modal isOpen={Boolean(transactionId)} onClose={onClose} title="Transaction Details" size="lg">
      {loading ? (
        <div className="flex justify-center py-10"><Loading /></div>
      ) : error ? (
        <div className="py-6 text-center">
          <p className="text-sm text-danger-600 mb-4">{error}</p>
          <Button variant="secondary" onClick={onClose}>Close</Button>
        </div>
      ) : (
        <TransactionDetailBody
          transaction={transaction}
          onEdit={onEdit}
          onDuplicate={onDuplicate}
          onDelete={onDelete}
        />
      )}
    </Modal>
  );
}
