import { useEffect, useRef } from 'react';
import Button from '../forms/Button';
import { formatMoney, formatDate } from '../../utils/format';

/**
 * Transactions table — desktop rows, mobile cards, row selection.
 *
 * The rows arrive already filtered, sorted and paged by the server; this
 * component never re-sorts or re-filters them. Date/Amount headers are
 * buttons that ask the parent to re-query with a whitelisted sort.
 */
const TYPE_BADGE = {
  INCOME: 'bg-green-50 text-green-700',
  EXPENSE: 'bg-danger-50 text-danger-700'
};

const amountClass = (type) =>
  type === 'INCOME' ? 'text-green-600' : 'text-danger-600';

function SortButton({ field, label, sortBy, sortOrder, onSort, align = 'left' }) {
  const active = sortBy === field;
  return (
    <button
      type="button"
      onClick={() => onSort(field)}
      className={`inline-flex items-center gap-1 font-medium hover:text-gray-900 ${align === 'right' ? 'justify-end w-full' : ''}`}
      title={`Sort by ${label.toLowerCase()}`}
    >
      {label}
      <span className={`text-xs ${active ? 'text-primary-600' : 'text-gray-300'}`} aria-hidden="true">
        {active ? (sortOrder === 'asc' ? '▲' : '▼') : '↕'}
      </span>
    </button>
  );
}

function RowActions({ onView, onEdit, onDuplicate, onDelete }) {
  return (
    <div className="flex items-center justify-end gap-1">
      <Button variant="ghost" size="sm" onClick={onView}>View</Button>
      <Button variant="ghost" size="sm" onClick={onEdit}>Edit</Button>
      <Button variant="ghost" size="sm" onClick={onDuplicate}>Duplicate</Button>
      <Button
        variant="ghost"
        size="sm"
        onClick={onDelete}
        className="text-danger-600 hover:bg-danger-50"
      >
        Delete
      </Button>
    </div>
  );
}

export default function TransactionTable({
  transactions,
  selected,
  onToggle,
  onToggleAll,
  onView,
  onEdit,
  onDuplicate,
  onDelete,
  sortBy,
  sortOrder,
  onSort
}) {
  const selectedSet = new Set(selected);
  const pageIds = transactions.map((t) => t.id);
  const allSelected = pageIds.length > 0 && pageIds.every((id) => selectedSet.has(id));
  const someSelected = !allSelected && pageIds.some((id) => selectedSet.has(id));

  const headerCheckbox = useRef(null);
  useEffect(() => {
    if (headerCheckbox.current) headerCheckbox.current.indeterminate = someSelected;
  }, [someSelected]);

  const categoryCell = (txn) =>
    txn.category ? (
      <span
        className="inline-flex items-center px-2 py-1 rounded-full text-xs font-medium"
        style={{ backgroundColor: `${txn.category.color}20`, color: txn.category.color }}
      >
        {txn.category.icon} {txn.category.name}
      </span>
    ) : (
      <span className="text-gray-300">—</span>
    );

  const autoBadge = (txn) =>
    txn.isAutoGenerated ? (
      <span className="ml-1.5 align-middle text-[10px] font-medium px-1.5 py-0.5 rounded bg-indigo-50 text-indigo-600">
        auto
      </span>
    ) : null;

  return (
    <>
      {/* Desktop / tablet */}
      <div className="hidden sm:block overflow-x-auto">
        <table className="w-full">
          <thead>
            <tr className="text-left text-sm text-gray-500 border-b border-gray-100">
              <th className="pb-3 pr-2 w-10">
                <input
                  ref={headerCheckbox}
                  type="checkbox"
                  checked={allSelected}
                  onChange={onToggleAll}
                  className="rounded border-gray-300 text-primary-600 focus:ring-primary-500"
                  aria-label={allSelected ? 'Deselect all on this page' : 'Select all on this page'}
                />
              </th>
              <th className="pb-3 font-medium" aria-sort={sortBy === 'date' ? (sortOrder === 'asc' ? 'ascending' : 'descending') : 'none'}>
                <SortButton field="date" label="Date" sortBy={sortBy} sortOrder={sortOrder} onSort={onSort} />
              </th>
              <th className="pb-3 font-medium">Description</th>
              <th className="pb-3 font-medium">Category</th>
              <th className="pb-3 font-medium">Account</th>
              <th className="pb-3 font-medium">Type</th>
              <th className="pb-3 font-medium text-right" aria-sort={sortBy === 'amount' ? (sortOrder === 'asc' ? 'ascending' : 'descending') : 'none'}>
                <SortButton field="amount" label="Amount" sortBy={sortBy} sortOrder={sortOrder} onSort={onSort} align="right" />
              </th>
              <th className="pb-3 font-medium text-right">Actions</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-gray-100">
            {transactions.map((txn) => (
              <tr key={txn.id} className={`hover:bg-gray-50 ${selectedSet.has(txn.id) ? 'bg-primary-50/40' : ''}`}>
                <td className="py-3 pr-2">
                  <input
                    type="checkbox"
                    checked={selectedSet.has(txn.id)}
                    onChange={() => onToggle(txn.id)}
                    className="rounded border-gray-300 text-primary-600 focus:ring-primary-500"
                    aria-label={`Select ${txn.description || txn.type}`}
                  />
                </td>
                <td className="py-3 text-sm text-gray-900 whitespace-nowrap">{formatDate(txn.date)}</td>
                <td className="py-3 text-sm text-gray-900">
                  {txn.description || '—'}
                  {autoBadge(txn)}
                </td>
                <td className="py-3">{categoryCell(txn)}</td>
                <td className="py-3 text-sm text-gray-600">{txn.account?.name || '—'}</td>
                <td className="py-3">
                  <span className={`text-xs font-medium px-2 py-1 rounded-full ${TYPE_BADGE[txn.type] || 'bg-gray-100 text-gray-600'}`}>
                    {txn.type === 'INCOME' ? 'Income' : 'Expense'}
                  </span>
                </td>
                <td className="py-3 text-sm font-medium text-right whitespace-nowrap">
                  <span className={amountClass(txn.type)}>
                    {txn.type === 'INCOME' ? '+' : '−'}{formatMoney(txn.amount, txn.account?.currency)}
                  </span>
                </td>
                <td className="py-3 text-right">
                  <RowActions
                    onView={() => onView(txn)}
                    onEdit={() => onEdit(txn)}
                    onDuplicate={() => onDuplicate(txn)}
                    onDelete={() => onDelete(txn)}
                  />
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {/* Mobile cards */}
      <ul className="sm:hidden divide-y divide-gray-100">
        {transactions.map((txn) => (
          <li key={txn.id} className={`py-3 ${selectedSet.has(txn.id) ? 'bg-primary-50/40' : ''}`}>
            <div className="flex items-start gap-3">
              <input
                type="checkbox"
                checked={selectedSet.has(txn.id)}
                onChange={() => onToggle(txn.id)}
                className="mt-1 rounded border-gray-300 text-primary-600 focus:ring-primary-500"
                aria-label={`Select ${txn.description || txn.type}`}
              />
              <div className="min-w-0 flex-1">
                <div className="flex items-start justify-between gap-3">
                  <div className="min-w-0">
                    <p className="text-sm font-medium text-gray-900 truncate">
                      {txn.description || 'No description'}
                      {autoBadge(txn)}
                    </p>
                    <p className="text-xs text-gray-500 mt-0.5">
                      {formatDate(txn.date)} · {txn.account?.name || '—'}
                    </p>
                    {txn.category && (
                      <span
                        className="inline-flex items-center mt-1.5 px-2 py-0.5 rounded-full text-xs font-medium"
                        style={{ backgroundColor: `${txn.category.color}20`, color: txn.category.color }}
                      >
                        {txn.category.icon} {txn.category.name}
                      </span>
                    )}
                  </div>
                  <div className="text-right shrink-0">
                    <p className={`text-sm font-semibold ${amountClass(txn.type)}`}>
                      {txn.type === 'INCOME' ? '+' : '−'}{formatMoney(txn.amount, txn.account?.currency)}
                    </p>
                    <span className={`text-[10px] font-medium px-1.5 py-0.5 rounded-full ${TYPE_BADGE[txn.type] || 'bg-gray-100 text-gray-600'}`}>
                      {txn.type === 'INCOME' ? 'Income' : 'Expense'}
                    </span>
                  </div>
                </div>
                <div className="mt-2 flex flex-wrap gap-1">
                  <Button variant="ghost" size="sm" onClick={() => onView(txn)}>View</Button>
                  <Button variant="ghost" size="sm" onClick={() => onEdit(txn)}>Edit</Button>
                  <Button variant="ghost" size="sm" onClick={() => onDuplicate(txn)}>Duplicate</Button>
                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={() => onDelete(txn)}
                    className="text-danger-600 hover:bg-danger-50"
                  >
                    Delete
                  </Button>
                </div>
              </div>
            </div>
          </li>
        ))}
      </ul>
    </>
  );
}
