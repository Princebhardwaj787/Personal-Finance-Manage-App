/**
 * Phase 7 frontend smoke test.
 *
 * Bundles the real Phase 7 modules with esbuild and renders them with
 * react-dom/server. This proves the new transactions/transfers screens, their
 * focused components and the recurring "generate" action all mount without
 * runtime errors, and asserts the query-layer helpers behave.
 *
 * Test-only accommodations because there is no DOM in Node:
 *  - a minimal `document`/`window`/`localStorage` stub (Modal.jsx and the auth
 *    context touch them)
 *  - an esbuild resolve shim that inlines `createPortal`, because React's
 *    server renderer rejects portals (error #200) before rendering them
 */
const path = require('path');
const os = require('os');
const fs = require('fs');

const clientDir = path.join(__dirname, 'client');
const esbuild = require(path.join(clientDir, 'node_modules', 'esbuild'));

const entry = `
import { renderToString } from 'react-dom/server';
import { createElement as h } from 'react';
import { MemoryRouter } from 'react-router-dom';

import Transactions from './src/pages/Transactions';
import Transfers, { TransferFormModal } from './src/pages/Transfers';
import RecurringExpenses from './src/pages/RecurringExpenses';
import Sidebar from './src/components/layout/Sidebar';
import AppRoutes from './src/routes/AppRoutes';
import TransactionFilters from './src/components/transactions/TransactionFilters';
import TransactionTable from './src/components/transactions/TransactionTable';
import TransactionFormModal from './src/components/transactions/TransactionFormModal';
import TransactionDetailModal, { TransactionDetailBody } from './src/components/transactions/TransactionDetailModal';
import { AuthProvider } from './src/contexts/AuthProvider';
import { buildQuery } from './src/services/api';
import { formatMoney, formatDate } from './src/utils/format';

const withRouter = (node, to = '/transactions') =>
  h(MemoryRouter, { initialEntries: [to] }, null, node);
const withAuth = (node, to = '/transactions') =>
  h(MemoryRouter, { initialEntries: [to] }, null, h(AuthProvider, null, node));

const noop = () => {};

const accounts = [
  { id: 'a1', name: 'HDFC Bank', type: 'BANK', balance: 45000, currency: 'INR', icon: null, color: null },
  { id: 'a2', name: 'Cash Wallet', type: 'CASH', balance: 3000, currency: 'INR', icon: null, color: null }
];

const expenseCategories = [
  { id: 'c1', name: 'Food & Dining', icon: '🍔', color: '#ef4444', type: 'EXPENSE' }
];
const incomeCategories = [
  { id: 'c2', name: 'Salary', icon: '💼', color: '#22c55e', type: 'INCOME' }
];

const txnExpense = {
  id: 't1', type: 'EXPENSE', amount: 820, description: 'Groceries',
  notes: 'Weekly shop at the big store', reference: 'UPI-9981',
  date: '2026-09-20T10:00:00.000Z', accountId: 'a1', categoryId: 'c1',
  account: accounts[0], category: expenseCategories[0],
  recurringExpenseId: 'r1',
  recurringExpense: { id: 'r1', name: 'Netflix', frequency: 'MONTHLY' },
  isAutoGenerated: true,
  createdAt: '2026-09-20T10:00:10.000Z', updatedAt: '2026-09-21T08:00:00.000Z'
};

const txnIncome = {
  id: 't2', type: 'INCOME', amount: 60000, description: 'September salary',
  notes: null, reference: null, date: '2026-09-01T05:30:00.000Z',
  accountId: 'a1', categoryId: 'c2', account: accounts[0], category: incomeCategories[0],
  recurringExpenseId: null, isAutoGenerated: false,
  createdAt: '2026-09-01T05:30:02.000Z', updatedAt: '2026-09-01T05:30:02.000Z'
};

const pagination = { page: 1, limit: 20, total: 25, totalPages: 2 };

const activeFilters = {
  search: 'groceries', type: 'EXPENSE', accountId: '', categoryId: 'c1',
  startDate: '2026-09-01', endDate: '', minAmount: '10', maxAmount: '',
  sortBy: 'date', sortOrder: 'desc'
};
const emptyFilters = {
  search: '', type: '', accountId: '', categoryId: '',
  startDate: '', endDate: '', minAmount: '', maxAmount: '',
  sortBy: 'date', sortOrder: 'desc'
};

const transferFixture = {
  id: 'tr1', amount: 5000, date: '2026-09-15T00:00:00.000Z',
  description: 'Move to savings', fromAccountId: 'a1', toAccountId: 'a2',
  fromAccount: accounts[0], toAccount: accounts[1]
};

const cases = [
  ['Transactions page (first render)', () => withRouter(h(Transactions))],
  ['Transfers page (first render)', () => withRouter(h(Transfers), '/transfers')],
  ['RecurringExpenses page (with generate action)', () => withRouter(h(RecurringExpenses), '/recurring-expenses')],
  ['Sidebar (Transactions + Transfers entries)', () => withAuth(h(Sidebar))],
  ['AppRoutes (/transfers resolves to a real route)', () => h(MemoryRouter, { initialEntries: ['/transfers'] }, null, h(AuthProvider, null, h(AppRoutes)))],
  ['Transactions page (type taken from ?type=INCOME)', () => {
    // The runner calls renderToString() after this factory returns, so the URL
    // is set here and cleared again once every case has rendered.
    globalThis.window.location.search = '?type=INCOME';
    return withRouter(h(Transactions));
  }],

  ['TransactionFilters (no filters -> no clear button)', () => h(TransactionFilters, {
    filters: emptyFilters, accounts, categories: [...expenseCategories, ...incomeCategories],
    onChange: noop, onClear: noop, pagination, count: 20
  })],
  ['TransactionFilters (filters active -> clear button)', () => h(TransactionFilters, {
    filters: activeFilters, accounts, categories: [...expenseCategories, ...incomeCategories],
    onChange: noop, onClear: noop, pagination, count: 2
  })],

  ['TransactionTable (rows, selection, sort)', () => h(TransactionTable, {
    transactions: [txnExpense, txnIncome], selected: ['t1'],
    onToggle: noop, onToggleAll: noop, onView: noop, onEdit: noop,
    onDuplicate: noop, onDelete: noop,
    sortBy: 'date', sortOrder: 'desc', onSort: noop
  })],
  ['TransactionTable (empty page)', () => h(TransactionTable, {
    transactions: [], selected: [], onToggle: noop, onToggleAll: noop,
    onView: noop, onEdit: noop, onDuplicate: noop, onDelete: noop,
    sortBy: 'amount', sortOrder: 'asc', onSort: noop
  })],

  ['TransactionFormModal (create)', () => h(TransactionFormModal, {
    open: true, onClose: noop, transaction: null, accounts,
    expenseCategories, incomeCategories, onSubmit: noop, submitting: false
  })],
  ['TransactionFormModal (edit with notes/reference)', () => h(TransactionFormModal, {
    open: true, onClose: noop, transaction: txnExpense, accounts,
    expenseCategories, incomeCategories, onSubmit: noop, submitting: true
  })],

  ['TransactionDetailBody (expense, auto-generated)', () => h(TransactionDetailBody, {
    transaction: txnExpense, onEdit: noop, onDuplicate: noop, onDelete: noop
  })],
  ['TransactionDetailBody (income, empty notes/reference)', () => h(TransactionDetailBody, {
    transaction: txnIncome, onEdit: noop, onDuplicate: noop, onDelete: noop
  })],
  ['TransactionDetailModal (closed renders nothing)', () => h(TransactionDetailModal, {
    transactionId: null, onClose: noop, onEdit: noop, onDuplicate: noop, onDelete: noop
  })],

  ['TransferFormModal (create)', () => h(TransferFormModal, {
    open: true, onClose: noop, transfer: null, accounts, onSubmit: noop, submitting: false
  })],
  ['TransferFormModal (edit)', () => h(TransferFormModal, {
    open: true, onClose: noop, transfer: transferFixture, accounts, onSubmit: noop, submitting: true
  })]
];

export function run() {
  // No DOM in Node: Modal.jsx reads document.body, axios/auth read localStorage.
  globalThis.document = {
    body: {},
    documentElement: { style: {} },
    addEventListener() {},
    removeEventListener() {},
    createElement: () => ({ style: {}, getBoundingClientRect: () => ({ width: 0, height: 0 }) })
  };
  globalThis.window = {
    devicePixelRatio: 1,
    location: { search: '', href: 'http://localhost/' },
    addEventListener() {},
    removeEventListener() {},
    matchMedia: () => ({ matches: false, addListener() {}, removeListener() {} }),
    getComputedStyle: () => ({ getPropertyValue: () => '' })
  };
  globalThis.localStorage = {
    getItem: () => null,
    setItem() {},
    removeItem() {},
    clear() {}
  };

  const results = [];
  for (const [name, make] of cases) {
    try {
      const html = renderToString(make());
      results.push({ name, ok: typeof html === 'string', html, len: html.length });
    } catch (err) {
      const stack = (err && err.stack ? String(err.stack) : '').split('\\n').slice(0, 4).join(' | ');
      results.push({
        name,
        ok: false,
        error: String(err && err.name) + ': ' + String(err && err.message) + ' >> ' + stack
      });
    }
  }
  globalThis.window.location.search = '';

  const htmlOf = (name) => {
    const hit = results.find((r) => r.name === name);
    return hit && hit.ok ? hit.html : '';
  };

  // React's server renderer separates text nodes with comment markers
  // ("Showing <!-- -->2<!-- --> of ..."), so strip them before matching text.
  const textOf = (name) => htmlOf(name).replace(/<!-- -->/g, '');

  const assert = [];
  const check = (name, condition, detail) => {
    assert.push({ name: name + (detail ? ' -- ' + detail : ''), ok: Boolean(condition) });
  };
  const containsAll = (html, needles) => needles.every((n) => html.indexOf(n) !== -1);

  // --- Required table columns (desktop + mobile card fallback) -------------
  const tableHtml = htmlOf('TransactionTable (rows, selection, sort)');
  check('Table has Date/Description/Category/Account/Type/Amount/Actions',
    containsAll(tableHtml, ['Date', 'Description', 'Category', 'Account', 'Type', 'Amount', 'Actions']));
  check('Table renders both transactions',
    containsAll(tableHtml, ['Groceries', 'September salary']));
  check('Auto-generated row carries its badge', tableHtml.indexOf('auto') !== -1);
  check('Mobile card layout exists (sm:hidden)', tableHtml.indexOf('sm:hidden') !== -1);
  check('Row selection state rendered', tableHtml.indexOf('checked') !== -1);
  check('Expense amount uses the minus sign + income the plus sign',
    tableHtml.indexOf('−') !== -1 && tableHtml.indexOf('+') !== -1);
  check('Sort indicator shown for the active column',
    tableHtml.indexOf('▼') !== -1 || tableHtml.indexOf('▲') !== -1);

  const emptyTableHtml = htmlOf('TransactionTable (empty page)');
  check('Empty table still renders column headers',
    containsAll(emptyTableHtml, ['Description', 'Amount', 'Actions']));

  // --- Filters -------------------------------------------------------------
  const filtersActive = htmlOf('TransactionFilters (filters active -> clear button)');
  const filtersIdle = htmlOf('TransactionFilters (no filters -> no clear button)');
  check('Filter bar shows the result count',
    textOf('TransactionFilters (filters active -> clear button)').indexOf('Showing 2 of 25') !== -1);
  check('Clear filters offered only when a filter is set',
    filtersActive.indexOf('Clear filters') !== -1 && filtersIdle.indexOf('Clear filters') === -1);
  check('Search box keeps the typed value', filtersActive.indexOf('value="groceries"') !== -1);
  check('Type filter exposes INCOME + EXPENSE only (no TRANSFER option)',
    filtersActive.indexOf('value="INCOME"') !== -1
    && filtersActive.indexOf('value="EXPENSE"') !== -1
    && filtersActive.indexOf('value="TRANSFER"') === -1);
  check('Amount range filters present',
    containsAll(filtersActive, ['Min amount', 'Max amount']));

  // --- Detail view ---------------------------------------------------------
  const detailHtml = htmlOf('TransactionDetailBody (expense, auto-generated)');
  check('Detail shows every user-facing field label',
    containsAll(detailHtml, ['Description', 'Category', 'Account', 'Notes', 'Reference',
      'Created', 'Last updated']));
  check('Detail shows notes + reference values',
    containsAll(detailHtml, ['Weekly shop at the big store', 'UPI-9981']));
  check('Detail shows the recurring source', detailHtml.indexOf('Netflix (MONTHLY)') !== -1);
  check('Detail marks auto-generated rows', detailHtml.indexOf('Auto-generated') !== -1);
  check('Detail exposes no internal fields', detailHtml.indexOf('userId') === -1);

  const incomeDetailHtml = htmlOf('TransactionDetailBody (income, empty notes/reference)');
  check('Detail renders em-dash for empty notes/reference',
    containsAll(incomeDetailHtml, ['Notes', 'Reference', '—']));
  check('Detail for income shows the Income badge', incomeDetailHtml.indexOf('Income') !== -1);

  check('Closed detail modal renders nothing',
    htmlOf('TransactionDetailModal (closed renders nothing)') === '');

  // --- Form ----------------------------------------------------------------
  const formCreateHtml = htmlOf('TransactionFormModal (create)');
  const formEditHtml = htmlOf('TransactionFormModal (edit with notes/reference)');
  check('Create form has notes + reference inputs',
    containsAll(formCreateHtml, ['Notes', 'Reference']));
  check('Edit form prefills notes + reference',
    containsAll(formEditHtml, ['Weekly shop at the big store', 'UPI-9981']));
  check('Form type toggle offers income and expense only',
    formEditHtml.indexOf('value="TRANSFER"') === -1 && formEditHtml.indexOf('Income') !== -1);
  check('Submitting state disables the submit button', formEditHtml.indexOf('disabled') !== -1);

  // --- Transfers -----------------------------------------------------------
  const transfersHtml = htmlOf('Transfers page (first render)');
  check('Transfers page explains the balance invariant',
    transfersHtml.indexOf('Effect on total balance') !== -1);
  check('Transfers page summarises movement and count',
    containsAll(transfersHtml, ['Moved in range', 'Transfers in range']));
  check('Transfers page filters by either side of the transfer',
    transfersHtml.indexOf('Either side') !== -1);
  check('Transfers page links back to transactions',
    transfersHtml.indexOf('/transactions') !== -1);
  check('Transfer form (create) renders source + destination selects',
    containsAll(htmlOf('TransferFormModal (create)'), ['From account', 'To account', 'New Transfer']));
  check('Transfer form (edit) prefills the description',
    htmlOf('TransferFormModal (edit)').indexOf('Move to savings') !== -1);

  // --- Recurring action ----------------------------------------------------
  const recurringHtml = htmlOf('RecurringExpenses page (with generate action)');
  check('Recurring page exposes the generate action',
    recurringHtml.indexOf('Generate due transactions') !== -1);
  check('Recurring page copy no longer claims rows are never created',
    recurringHtml.indexOf('do not create transactions') === -1);

  // --- Navigation ----------------------------------------------------------
  const sidebarHtml = htmlOf('Sidebar (Transactions + Transfers entries)');
  check('Sidebar links Transactions', sidebarHtml.indexOf('/transactions') !== -1);
  check('Sidebar links Transfers', sidebarHtml.indexOf('/transfers') !== -1);

  const transfersRouteHtml = htmlOf('AppRoutes (/transfers resolves to a real route)');
  // A missing path falls through to the wildcard <Navigate> (renders nothing in
  // SSR), so any output here proves /transfers matched a concrete route and
  // stopped at the auth loading screen.
  check('Route /transfers exists (no wildcard redirect)',
    transfersRouteHtml.length > 0 && transfersRouteHtml.indexOf('/login') === -1,
    'len=' + transfersRouteHtml.length);
  const typeParamHtml = htmlOf('Transactions page (type taken from ?type=INCOME)');
  check('?type=INCOME activates the type filter on first render',
    typeParamHtml.indexOf('Clear filters') !== -1,
    'len=' + typeParamHtml.length);

  // --- Query layer (reused by any future export) ---------------------------
  check('buildQuery drops empty values',
    buildQuery({ type: '', startDate: undefined, search: null }) === '');
  check('buildQuery keeps set values',
    buildQuery({ type: 'EXPENSE', page: 1, search: 'groceries' }) === '?type=EXPENSE&page=1&search=groceries',
    buildQuery({ type: 'EXPENSE', page: 1, search: 'groceries' }));
  check('buildQuery URL-encodes the search term',
    buildQuery({ search: 'a b&c' }) === '?search=a+b%26c', buildQuery({ search: 'a b&c' }));

  check('formatMoney is currency aware', formatMoney(1234, 'INR').indexOf('1,234') !== -1,
    formatMoney(1234, 'INR'));
  check('formatMoney survives an unknown currency', typeof formatMoney(10, 'ZZZ') === 'string');
  check('formatMoney handles empty amounts', formatMoney(null) === '0');
  check('formatDate renders a readable date', formatDate('2026-09-20T10:00:00.000Z').length > 6);

  return { renders: results, checks: assert };
}
`;

async function main() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pfm-smoke7-'));
  const entryPath = path.join(clientDir, '.phase7_smoke_entry.jsx');
  const outPath = path.join(tmp, 'bundle.cjs');

  fs.writeFileSync(entryPath, entry, 'utf8');
  const shimPath = path.join(tmp, 'portal-shim.mjs');
  fs.writeFileSync(shimPath, 'export const createPortal = (children) => children;\n', 'utf8');

  try {
    await esbuild.build({
      entryPoints: [entryPath],
      outfile: outPath,
      bundle: true,
      platform: 'node',
      format: 'cjs',
      jsx: 'automatic',
      absWorkingDir: clientDir,
      nodePaths: [path.join(clientDir, 'node_modules')],
      plugins: [
        {
          name: 'portal-shim',
          setup(build) {
            // Exact match only, so 'react-dom/server' still resolves normally.
            build.onResolve({ filter: /^react-dom$/ }, () => ({ path: shimPath }));
          }
        }
      ],
      define: { 'process.env.NODE_ENV': '"production"' },
      logLevel: 'error'
    });
  } finally {
    fs.rmSync(entryPath, { force: true });
  }

  const { run } = require(outPath);
  const { renders, checks } = run();

  // Route configuration is checked against the source: during SSR the auth
  // context never finishes loading, so a redirect component renders nothing.
  const routesSrc = fs.readFileSync(path.join(clientDir, 'src', 'routes', 'AppRoutes.jsx'), 'utf8');
  const pushSourceCheck = (name, ok, detail) => {
    checks.push({ name: name + (detail ? ' -- ' + detail : ''), ok: Boolean(ok) });
  };
  pushSourceCheck('Route /transfers is registered',
    routesSrc.includes('<Route path="/transfers"'));
  pushSourceCheck('/income redirects to the transactions screen filtered by type',
    routesSrc.includes('<Route path="/income"') && routesSrc.includes('/transactions?type=INCOME'));
  pushSourceCheck('/expenses redirects to the transactions screen filtered by type',
    routesSrc.includes('<Route path="/expenses"') && routesSrc.includes('/transactions?type=EXPENSE'));
  pushSourceCheck('No stale placeholder routes remain',
    !routesSrc.includes('Coming in Phase 3'));

  let failed = 0;
  console.log('=== PHASE 7 · FRONTEND SMOKE ===\n');
  console.log('Component renders');
  for (const r of renders) {
    if (r.ok) {
      console.log(`  ok   ${r.name}${r.len === 0 ? ' (renders nothing, as expected)' : ''}`);
    } else {
      failed += 1;
      console.log(`  FAIL ${r.name} -- ${r.error}`);
    }
  }

  console.log('\nContent + query layer');
  for (const c of checks) {
    if (c.ok) console.log(`  ok   ${c.name}`);
    else { failed += 1; console.log(`  FAIL ${c.name}`); }
  }

  const total = renders.length + checks.length;
  console.log(`\n=== FRONTEND SMOKE: ${total - failed} passed, ${failed} failed ===`);
  process.exit(failed > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error('Smoke test crashed:', err);
  process.exit(1);
});
